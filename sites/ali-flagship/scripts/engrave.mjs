// Cuts an engraved line-screen plate from Ali's studio portrait. No image model: the photo's own
// tones set the width of each engraved line, the way an intaglio portrait is cut.
// Usage: node scripts/engrave.mjs <photo-clean>
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';

const [, , src] = process.argv;
const RATIO = 1199 / 1312;
const INK = [237, 230, 214];
const GROUND = [8, 13, 21];
const clamp = (v) => Math.max(0, Math.min(1, v));
const FLOOR = Number(process.env.FLOOR ?? 0.15);
const GAMMA = Number(process.env.GAMMA ?? 1.3);

async function plate(W) {
  const SS = 3; // supersample, then scale down for clean edges
  const w = W * SS;
  const h = Math.round(W * RATIO) * SS;
  const grey = await sharp(src)
    .resize(w, h, { fit: 'fill' })
    .greyscale()
    .normalise({ lower: 1, upper: 99.5 })
    .clahe({ width: Math.round(w / 9), height: Math.round(w / 9), maxSlope: 3 })
    .blur(SS * 0.5)
    .raw()
    .toBuffer();
  const out = Buffer.alloc(w * h * 3);
  const p1 = (W / 128) * SS; // main screen pitch
  const p2 = p1 * 1.02;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      // Studio background and jacket fall below the floor and keep only a hairline.
      const L = Math.pow(clamp((grey[y * w + x] / 255 - FLOOR) / (0.97 - FLOOR)), GAMMA);
      // main screen: long, slightly waving lines
      const yy = y + 1.5 * p1 * Math.sin(x / (p1 * 27)) + 0.6 * p1 * Math.sin((x + y * 0.6) / (p1 * 9));
      const d1 = Math.abs((((yy / p1) % 1) + 1) % 1 - 0.5) * 2;
      const w1 = 0.07 + 0.76 * L;
      let a = clamp(0.5 + ((w1 - d1) * p1) / 4);
      // cross screen: only where the light is strong
      const u = x * 0.5 + y * 0.866;
      const d2 = Math.abs((((u / p2) % 1) + 1) % 1 - 0.5) * 2;
      const w2 = clamp((L - 0.6) * 2.2) * 0.62;
      const a2 = w2 > 0.02 ? clamp(0.5 + ((w2 - d2) * p2) / 4) : 0;
      a = Math.max(a, a2);
      const i = (y * w + x) * 3;
      out[i] = GROUND[0] + (INK[0] - GROUND[0]) * a;
      out[i + 1] = GROUND[1] + (INK[1] - GROUND[1]) * a;
      out[i + 2] = GROUND[2] + (INK[2] - GROUND[2]) * a;
    }
  }
  const img = sharp(out, { raw: { width: w, height: h, channels: 3 } }).resize(W);
  const stem = `public/art/ali-plate-${W}`;
  await img.clone().avif({ quality: 55, effort: 6 }).toFile(`${stem}.avif`);
  await img.clone().webp({ quality: 80, effort: 6 }).toFile(`${stem}.webp`);
  const meta = JSON.stringify({ prompt: 'Origin: engraved line-screen plate cut by scripts/engrave.mjs from the studio portrait supplied by Ali Nojoumi. Not generated by an image model.', createdAt: '2026-11-10' }, null, 2);
  await writeFile(`${stem}.avif.json`, meta);
  await writeFile(`${stem}.webp.json`, meta);
  console.log('plate', W);
}

for (const W of [640, 1280]) await plate(W);
