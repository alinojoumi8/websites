// Turns the raw Krea renders and Ali's photos into the files the site ships.
// Usage: node scripts/images.mjs <photo-clean> <photo-minis>
// Raw files live in ./raw (git-ignored). Each output gets a provenance sidecar.
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const [, , photoClean, photoMinis] = process.argv;
const out = 'public/art';
await mkdir(out, { recursive: true });

const STYLE =
  'Abstract 3D render in the style of macro product photography. Materials: dark blued steel engraved with ultra-fine banknote-style guilloche line patterns, colour-shifting foil, clear polished glass. Deep midnight-navy, near-black background. One warm amber key light from the upper right, faint cool steel-blue fill, shallow depth of field with soft amber bokeh. No text, no logos, no people.';

const krea = (subject) => ({
  prompt: `${subject} ${STYLE}`,
  model: 'google/nano-banana-pro via Krea',
  createdAt: '2026-11-10',
});
const photo = (what) => ({
  prompt: `Origin: ${what}, supplied by Ali Nojoumi. Not generated for this site.`,
  createdAt: '2026-11-10',
});

const jobs = [
  { src: 'raw/hero.png', name: 'hero', widths: [2400, 1600, 960], meta: krea('A monumental guilloche rosette engraved into a dark blued-steel printing plate at a low three-quarter angle; a wide ribbon of optically variable foil, copper-gold to emerald, arcs above it; the left third falls into darkness.') },
  { src: 'raw/plate.jpg', name: 'plate', widths: [1200, 800], meta: krea('Flat top-down macro of a dark blued-steel printing plate covered edge to edge with engraved guilloche line-work, soft raking light, low contrast background texture.') },
  { src: 'raw/pontemesto.png', name: 'pontemesto', widths: [1200, 720], meta: krea('A bridge arch built from ribbons of engraved steel spanning a gap between two plates; a stream of small copper-gold discs flows across the deck; a foil strip runs along its edge.') },
  { src: 'raw/keywa.jpg', name: 'keywa', widths: [1200, 720], meta: krea('A circular vault mechanism of three interlocking engraved steel ring segments about to close around a glowing emerald glass core; foil lines the inner edges.') },
  { src: 'raw/manyworld.jpg', name: 'manyworld', widths: [1200, 720], meta: krea('A miniature world: a sphere built from hundreds of tiny engraved steel tiles, towers and copper-gold discs like a city with trade routes; two foil orbits circle it.') },
  { src: 'raw/triallens.png', name: 'triallens', widths: [1200, 720], meta: krea('A thick clear glass magnifying lens on a slim steel stand over an engraved plate; it bends the guilloche lines and one magnified line glows emerald; foil wraps the rim.') },
  { src: 'raw/crowdlens.png', name: 'crowdlens', widths: [1200, 720], meta: krea('A dense crowd of tiny pawn-like engraved steel figures on a plate; a ripple of emerald light travels through them; one arc of foil sweeps overhead.') },
];
if (photoClean) jobs.push({ src: photoClean, name: 'ali', widths: [1312, 800], meta: photo('studio portrait of Ali Nojoumi') });
if (photoMinis) jobs.push({ src: photoMinis, name: 'ali-minis', widths: [1312, 800], meta: photo('composite portrait of Ali Nojoumi with seven small copies of himself') });

for (const j of jobs) {
  for (const w of j.widths) {
    const base = sharp(j.src).resize({ width: w, withoutEnlargement: true });
    const stem = join(out, `${j.name}-${w}`);
    await base.clone().avif({ quality: 52, effort: 6 }).toFile(`${stem}.avif`);
    await base.clone().webp({ quality: 78, effort: 6 }).toFile(`${stem}.webp`);
    for (const ext of ['avif', 'webp']) await writeFile(`${stem}.${ext}.json`, JSON.stringify(j.meta, null, 2));
  }
  console.log('done', j.name);
}

// Fine film grain tile, made here from noise. No image model.
const size = 128;
const buf = Buffer.alloc(size * size * 4);
let s = 1337;
const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
for (let i = 0; i < size * size; i++) {
  const v = Math.round(rnd() * 255);
  buf[i * 4] = buf[i * 4 + 1] = buf[i * 4 + 2] = v;
  buf[i * 4 + 3] = Math.round(40 + rnd() * 70);
}
await sharp(buf, { raw: { width: size, height: size, channels: 4 } }).webp({ quality: 50 }).toFile(join(out, 'grain.webp'));
await writeFile(join(out, 'grain.webp.json'), JSON.stringify({ prompt: 'Origin: random noise tile written by scripts/images.mjs. Not generated by an image model.', createdAt: '2026-11-10' }, null, 2));
console.log('done grain');
